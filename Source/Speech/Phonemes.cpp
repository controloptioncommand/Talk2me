const PhonDef& phon (Ph p) { return table[p < NumPh ? p : PAU]; }

bool isVowel (Ph p)
{
    const auto k = phon (p).kind;
    return k == Kind::Vowel || k == Kind::Diphthong;
}

bool isConsonant (Ph p) { return p != PAU && ! isVowel (p); }

Ph phFromName (const std::string& n)
{
    for (int i = 0; i < NumPh; ++i)
        if (n == table[i].name) return (Ph) i;
    return NumPh;
}
